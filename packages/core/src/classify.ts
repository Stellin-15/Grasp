/**
 * Files whose contents Grasp never reads, regardless of config.
 * Why: Grasp output can later be sent to an LLM, so secrets must not enter the fact base at all.
 */
const SECRET_PATTERNS: RegExp[] = [
  /(^|\/)\.env(\.[^/]*)?$/,
  /\.(pem|key|p12|pfx|jks|keystore|ppk|asc|gpg)$/i,
  /(^|\/)id_(rsa|dsa|ecdsa|ed25519)(\.pub)?$/,
  /(^|\/)\.(netrc|npmrc|pypirc|htpasswd)$/,
  /(^|\/)credentials(\.json)?$/i,
  /(^|\/)secrets?\.(json|ya?ml|toml)$/i,
];

/** Template files document variable names without values, so they are safe and useful. */
const SECRET_EXCEPTIONS = /(^|\/)\.env\.(example|sample|template|dist|defaults)$/;

export function isSecretPath(path: string): boolean {
  if (SECRET_EXCEPTIONS.test(path)) return false;
  return SECRET_PATTERNS.some((re) => re.test(path));
}

